(() => {
  const STYLE_ID = 'signup-consent-layout-style';

  function installStyles() {
    if (document.getElementById(STYLE_ID)) return;
    const style = document.createElement('style');
    style.id = STYLE_ID;
    style.textContent = `
      .auth-card.wide .auth-legal { display:none !important; }
      .auth-card.wide .dpdp-consent-panel {
        order: 0 !important;
        width: 100% !important;
        max-height: 132px !important;
        overflow-y: auto !important;
        overflow-x: hidden !important;
        margin: 14px 0 0 !important;
        padding: 11px 12px !important;
        border: 1px solid #e1e6ee !important;
        border-radius: 10px !important;
        background: #fafbfd !important;
        font-size: 10px !important;
        line-height: 1.42 !important;
        scrollbar-width: thin !important;
      }
      .auth-card.wide .dpdp-consent-panel::-webkit-scrollbar { width: 6px; }
      .auth-card.wide .dpdp-consent-panel::-webkit-scrollbar-thumb { background:#cbd2dd; border-radius:99px; }
      .auth-card.wide .dpdp-consent-title { font-size: 11px !important; margin-bottom: 4px !important; color:#202938 !important; }
      .auth-card.wide .dpdp-consent-panel p { margin:0 0 7px !important; }
      .auth-card.wide .dpdp-consent-panel label { margin:6px 0 !important; gap:7px !important; }
      .auth-card.wide .dpdp-consent-panel input[type="checkbox"] { flex:0 0 auto; margin-top:2px !important; }
      .auth-card.wide .dpdp-consent-links { margin-top:7px !important; gap:6px !important; }
      .auth-card.wide .dpdp-consent-error { margin-top:5px !important; }
    `;
    document.head.appendChild(style);
  }

  function arrange() {
    const form = document.querySelector('.auth-card.wide form');
    const panel = form?.querySelector('.dpdp-consent-panel');
    if (!form || !panel) return;

    installStyles();

    // Remove the old standalone legal sentence generated by the auth redesign.
    form.querySelectorAll('.auth-legal').forEach((el) => el.remove());

    // Put the compact consent drawer immediately below the Create account button.
    const primary = form.querySelector('button.primary.full, button.primary');
    if (primary && panel.previousElementSibling !== primary) {
      primary.insertAdjacentElement('afterend', panel);
    }

    // Keep the existing consent validation and links; only the presentation/order changes.
    panel.dataset.layoutFixed = '1';
  }

  const observer = new MutationObserver(arrange);
  observer.observe(document.documentElement, { childList: true, subtree: true });
  installStyles();
  arrange();
})();
